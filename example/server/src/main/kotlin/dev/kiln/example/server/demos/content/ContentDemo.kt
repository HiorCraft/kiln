import dev.kiln.server.api.entity.CustomEntityType

/**
 * Content from extension resources (extension `kiln_content`, assets generated by `tools/gen_content_assets.py`):
 * - custom item "Rubin" with its own model and texture; right click plays the custom sound `ruby_chime`;
 * - custom enchantment `kiln_content:lifesteal` (registered in [dev.kiln.example.server.ExampleBootstrap]);
 * - bitmap font `kiln_content:runes` in chat (and in the extension's HUD label);
 * - post effect `kiln_content:ruby_vision`.
 *
 * `/kiln give ruby|lifesteal_sword`, `/kiln font`, `/kiln effect [ruby_vision|off]`.
 */
class ContentDemo(private val plugin: JavaPlugin) : TabExecutor {
    private val kiln = Kiln.get()
    val extension: Extension = plugin.registerExtension("kiln_content")

    private lateinit var golem: CustomEntityType

    private val ruby = kiln.items.register(plugin, extension.key("ruby")) {
        name = Component.text("Rubin", NamedTextColor.RED)
        lore = listOf(Component.text("Rechtsklick: klingt", NamedTextColor.GRAY))
        components { set(DataComponentTypes.MAX_STACK_SIZE, 16) }
        onUse { player, _, _ ->
            player.playSound(Sound.sound(extension.key("ruby_chime"), Sound.Source.PLAYER, 1f, 1f))
        }
    }

    // furniture: item + type; the bench has two solid hit boxes (composite), all of them can be sat on
    private val chairItem = furnitureItem("chair", "Stuhl")
    private val tableItem = furnitureItem("table", "Tisch")
    private val benchItem = furnitureItem("bench", "Bank")

    private fun furnitureItem(name: String, title: String) = kiln.items.register(plugin, extension.key(name)) {
        this.name = Component.text(title, NamedTextColor.GOLD)
        lore = listOf(Component.text("Rechtsklick auf einen Block: aufstellen", NamedTextColor.GRAY))
    }

    init {
        kiln.furniture.register(plugin, extension.key("chair")) {
            item = chairItem
            hitbox(width = 0.9, height = 0.6, solid = true)
            // backrest (2/16 deep, at the back = north): interaction boxes have a square base, so four slim columns
            for (x in listOf(-0.33, -0.11, 0.11, 0.33)) hitbox(width = 0.22, height = 0.775, offset = Vector(x, 0.6, -0.375), solid = true)
            seat(Vector(0.0, 0.625, 0.0)) // seat surface 10/16
        }
        kiln.furniture.register(plugin, extension.key("table")) {
            item = tableItem
            hitbox(width = 1.0, height = 1.0, solid = true)
        }
        kiln.furniture.register(plugin, extension.key("bench")) {
            item = benchItem
            hitbox(width = 1.0, height = 0.5, offset = Vector(-0.5, 0.0, 0.0), solid = true)
            hitbox(width = 1.0, height = 0.5, offset = Vector(0.5, 0.0, 0.0), solid = true)
            // three places; a right click sits on the free one closest to the clicked point
            for (x in listOf(-0.67, 0.0, 0.67)) seat(Vector(x, 0.5, 0.0)) // seat surface 8/16
        }
        kiln.creativeTabs.register(plugin, extension.key("inhalte")) {
            title = Component.text("Kiln Inhalte", NamedTextColor.RED)
            icon = { ruby.create() }
            add(ruby, chairItem, tableItem, benchItem)
            add { lifestealSword() }
        }
        kiln.creativeTabs.addToVanillaTab(plugin, CreativeTabs.INGREDIENTS) { listOf(ruby.create()) }

        // custom entity: stone golem with bone model, animations, own hit box and behaviour
        golem = kiln.entities.register(plugin, extension.key("golem")) {
            displayName = Component.text("Steingolem", NamedTextColor.GRAY)
            width = 1.6
            height = 2.9
            health = 80.0
            speed = 0.22
            // vanilla iron golem sounds, a bit deeper (keys of extension sounds work the same)
            sounds {
                ambient = Key.key("minecraft", "entity.iron_golem.repair")
                hurt = Key.key("minecraft", "entity.iron_golem.hurt")
                death = Key.key("minecraft", "entity.iron_golem.death")
                step = Key.key("minecraft", "entity.iron_golem.step")
                stepInterval = 12
                pitch = 0.8f
            }
            behavior {
                targeting(range = 16.0)
                // smash: wind up, slam, damage and knock back everything close, then a cooldown
                goal(1, "smash") {
                    canStart { target?.let { distanceTo(it) < 3.2 } == true && cooldownReady("smash") }
                    sequence {
                        stopMoving()
                        animate("smash")
                        wait(10)
                        run {
                            playSound(Key.key("minecraft", "entity.iron_golem.attack"), 1.2f, 0.7f)
                            val damage = if (state == "enraged") 12.0 else 8.0
                            for (player in nearbyPlayers(3.6)) {
                                damage(player, damage)
                                player.velocity = player.location.toVector().subtract(self.location.toVector()).setY(0).normalize().multiply(0.9).setY(0.45)
                            }
                        }
                        wait(6)
                        run { cooldown("smash", if (state == "enraged") 30 else 50) }
                    }
                }
                goal(2, "chase") { chaseTarget(speed = 1.0, distance = 2.4) }
                goal(5, "wander") { wander(radius = 8) }
                goal(6, "look") { lookAtNearestPlayer(10.0) }
                // below 30 health: roar once, then faster and harder
                state("enraged") {
                    onEnter {
                        animate("roar")
                        playSound(Key.key("minecraft", "entity.ravager.roar"), 1.5f, 0.8f)
                        self.getAttribute(Attribute.MOVEMENT_SPEED)?.baseValue = 0.3
                    }
                }
            }
            onDamage { _, _ -> if (state != "enraged" && self.health < 30.0) switchTo("enraged") }
            onDeath { self.world.dropItemNaturally(self.location, ruby.create(3)) }
        }

        kiln.enchantments.onHit(plugin, LIFESTEAL) { attacker, _, level, event ->
            // heals 20 % of the dealt damage per level
            val max = attacker.getAttribute(Attribute.MAX_HEALTH)?.value ?: return@onHit
            attacker.health = (attacker.health + event.finalDamage * 0.2 * level).coerceAtMost(max)
        }
    }

    private fun lifestealSword(): ItemStack {
        val sword = ItemType.IRON_SWORD.createItemStack()
        val enchantment = RegistryAccess.registryAccess().getRegistry(RegistryKey.ENCHANTMENT).get(LIFESTEAL)
        if (enchantment != null) sword.addEnchantment(enchantment, 3)
        return sword
    }

    override fun onCommand(sender: CommandSender, command: Command, label: String, args: Array<out String>): Boolean {
        val player = ExampleCommands.requirePlayer(sender) ?: return true
        when (args.getOrNull(0)) {
            "give" -> when (args.getOrNull(1)) {
                "ruby" -> player.inventory.addItem(ruby.create(4))
                "lifesteal_sword" -> player.inventory.addItem(lifestealSword())
                "chair" -> player.inventory.addItem(chairItem.create())
                "table" -> player.inventory.addItem(tableItem.create())
                "bench" -> player.inventory.addItem(benchItem.create())
                else -> return false
            }
            "spawn" -> when (args.getOrNull(1)) {
                "golem" -> golem.spawn(player.location.clone().add(player.location.direction.setY(0).normalize().multiply(4)))
                else -> return false
            }
            "font" -> {
                player.sendMessage(Component.text("KILN RUNEN SIND DA").font(extension.key("runes")).color(NamedTextColor.RED))
                player.sendMessage(Component.text("(Schrift kiln_content:runes aus den Server-Ressourcen)", NamedTextColor.GRAY))
            }
            "effect" -> {
                val effect = when (args.getOrNull(1) ?: "ruby_vision") {
                    "off" -> null
                    "ruby_vision" -> extension.key("ruby_vision")
                    else -> return false
                }
                kiln.setPostEffect(player, effect)
            }
            else -> return false
        }
        return true
    }

    override fun onTabComplete(sender: CommandSender, command: Command, label: String, args: Array<out String>): List<String> =
        when (args.size) {
            1 -> listOf("give", "spawn", "font", "effect")
            2 -> when (args[0]) {
                "give" -> listOf("ruby", "lifesteal_sword", "chair", "table", "bench")
                "effect" -> listOf("ruby_vision", "off")
                "spawn" -> listOf("golem")
                else -> emptyList()
            }
            else -> emptyList()
        }.filter { it.startsWith(args.last()) }

    companion object {
        val LIFESTEAL: Key = Key.key("kiln_content", "lifesteal")
    }
}
